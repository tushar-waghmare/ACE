#ifndef ACE_TESTS_TEST_TOOLS_DEFINED_H
#define ACE_TESTS_TEST_TOOLS_DEFINED_H

//Minimal test harness: plain checks, no dependencies beyond ACE/Eigen.
//Run all tests with 'make tests' (from the repository root).

#include <iostream>
#include <string>
#include <cmath>
#include <random>
#include <sstream>
#include <iomanip>
#include <Eigen/Dense>

namespace ACE_tests{

//short scientific formatting for messages
inline std::string sci(double x){
  std::ostringstream ss; ss<<std::scientific<<std::setprecision(2)<<x; return ss.str();
}

inline int &n_failed(){ static int n=0; return n; }

inline void check(bool ok, const std::string &what){
  std::cout<<(ok?"PASS  ":"FAIL  ")<<what<<std::endl;
  if(!ok)n_failed()++;
}

//relative deviation |a-b|/max(|a|,|b|,floor)
inline double rel_dev(std::complex<double> a, std::complex<double> b, double floor=1e-300){
  double s=std::max(std::max(std::abs(a), std::abs(b)), floor);
  return std::abs(a-b)/s;
}

inline Eigen::MatrixXcd random_matrix(int rows, int cols, std::mt19937 &rng){
  std::normal_distribution<double> dist(0.,1.);
  Eigen::MatrixXcd M(rows, cols);
  for(int i=0; i<rows; i++){
    for(int j=0; j<cols; j++){
      M(i,j)=std::complex<double>(dist(rng), dist(rng));
    }
  }
  return M;
}

//bilinear pairing (no conjugation)
inline std::complex<double> pair(const Eigen::MatrixXcd &chi, const Eigen::MatrixXcd &psi){
  return chi.cwiseProduct(psi).sum();
}

inline int finish(const std::string &name){
  if(n_failed()>0){
    std::cout<<name<<": "<<n_failed()<<" check(s) FAILED"<<std::endl;
    return 1;
  }
  std::cout<<name<<": all checks passed"<<std::endl;
  return 0;
}

//PT generated by 'make tests' from tests/data/small_PT.param
inline std::string small_PT(){ return "tests/data/small.pt"; }

}//namespace
#endif
