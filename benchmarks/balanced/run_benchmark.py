"""
Benchmark: SVD vs protected operational balanced truncation at equal bond dimension.

    python3 benchmarks/balanced/run_benchmark.py --pt smoke.pt --te 5 --outdir out_pilot

(run from the repository root; needs bin/ACE, tools/PTB_sweep_forward,
tools/PTB_sweep_backward, tools/PTB_balanced_truncate; stdlib only).

Steps
  1. generate a family of pulsed contexts (Gaussian pulses, random area and detuning),
     split into training and held-out sets (seeded), plus an out-of-distribution
     set (two pulses, random pure initial states) never used for training;
  2. reference: every context through the input PT (add_PT);
  3. for each maxk: SVD baseline (backward sweep without truncation, forward sweep
     with compress_maxk) and balanced truncation (PTB_balanced_truncate with the
     training contexts, for each eta);
  4. every context through every truncated PT; errors w.r.t. the reference.

Outputs (in --outdir): results.csv (one row per method/maxk/eta/set), per-cut
diagnostics balanced_<maxk>_<eta>.csv, the generated context files.

Metrics per row: rms_final (RMS over contexts of the final-time observable error),
rms_trace (RMS over contexts and times of the observable time trace error),
max_trace_err (max |tr rho_S(t) - 1|), max_population_drift (max |rho_11(t) - rho_11(0)|,
exactly 0 for pure dephasing), maxdim, hs_rel (||T - T_trunc||_HS / ||T||_HS), runtime_s, and for balanced runs
max/median ||X||*||Y|| and the sum of local operational errors; certificate_train (balanced runs, training
row only): global ensemble certificate of the sweep, an upper bound on that row's rms_final (equal weights,
final time, relative to the input PT; free since pasts and futures use the same training list;
balanced_<maxk>_<eta>_cert.csv).

Large PTs (all optional; results are identical, see tests/test_balanced_stream_cache.cpp):
  --batched     simulations with tools/PTB_simulate_contexts: one pass over the PT per --jobs chunk of
                contexts instead of one bin/ACE run (one full read of the PT) per context;
  --stream      PTB_balanced_truncate -stream true: no full working copy of the input PT on disk;
  --cache_dir   maxk/eta-independent quantities of the input PT, computed once and reused: operational
                future factors per training set, HS future factors, log ||T||_HS, maxdim of the input;
  --stage       split a run into prep (contexts, reference, caches), svd (SVD arm) and balanced
                (balanced arm); svd/balanced write results_svd.csv / results_balanced.csv
                (hpc/merge_results.py merges them); 'all' (default) = everything, results.csv.
timings.csv (outdir): wall-clock seconds per phase (reference, truncation, simulations, HS distance, ...);
balanced_<maxk>_<eta>_timing.csv: phases inside PTB_balanced_truncate.
Before running, the build of the tools is checked against the checkout (--allow_stale_build to skip).
"""
