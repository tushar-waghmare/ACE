"""
Benchmark: SVD vs protected operational balanced truncation at equal bond dimension.

    python3 benchmarks/balanced/run_benchmark.py --pt smoke.pt --te 5 --outdir out_pilot

(run from the repository root; needs bin/ACE, tools/PTB_sweep_forward,
tools/PTB_sweep_backward, tools/PTB_balanced_truncate; stdlib only).

Steps
  1. generate a family of pulsed contexts (Gaussian pulses, random area and detuning),
     split into training and held-out sets (seeded), plus an out-of-distribution
     set (two pulses, random pure initial states) never used for training;
  2. reference: every context through the input PT (add_PT);
  3. for each maxk: SVD baseline (backward sweep without truncation, forward sweep
     with compress_maxk) and balanced truncation (PTB_balanced_truncate with the
     training contexts, for each eta);
  4. every context through every truncated PT; errors w.r.t. the reference.

Outputs (in --outdir): results.csv (one row per method/maxk/eta/set), per-cut
diagnostics balanced_<maxk>_<eta>.csv, the generated context files.

Metrics per row: rms_final (RMS over contexts of the final-time observable error),
rms_trace (RMS over contexts and times of the observable time trace error),
max_trace_err (max |tr rho_S(t) - 1|), max_population_drift (max |rho_11(t) - rho_11(0)|,
exactly 0 for pure dephasing), maxdim, hs_rel (||T - T_trunc||_HS / ||T||_HS), runtime_s, and for balanced runs
max/median ||X||*||Y|| and the sum of local operational errors.
"""
import argparse
import csv
import math
import os
import random
import shutil
import statistics
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
ACE = os.path.join(ROOT, 'bin', 'ACE')
TOOLS = os.path.join(ROOT, 'tools')


def run(cmd, cwd=None):
    t0 = time.time()
    p = subprocess.run(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if p.returncode != 0:
        sys.stderr.write(p.stdout)
        raise RuntimeError(f"command failed: {' '.join(cmd)}")
    return time.time() - t0, p.stdout


def write_context(path, area, detuning, t0, tau, te, dt, nintermediate,
                  initial='{|0><0|_2}', obs='|1><1|_2'):
    with open(path, 'w') as f:
        f.write(f"""# generated by run_benchmark.py: area={area:.6f} pi, detuning={detuning:.6f}
ta {0}
dt {dt}
te {te}
Nintermediate {nintermediate}
initial          {initial}
add_Hamiltonian  {{-1.5*|1><1|_2}}
add_Pulse Gauss  {t0} {tau} {{{area:.10f}*pi}} {detuning:.10f}   {{hbar/2*|1><0|_2}}
{OUTPUTS.format(obs=obs)}""")


MIXED_OBSERVABLES = ['|1><1|_2', '|1><1|_2', '|0><1|_2+|1><0|_2', '-i*|0><1|_2+i*|1><0|_2']


# first output = observable (used for training), then populations (trace, drift)
OUTPUTS = """add_Output       {{{obs}}}
add_Output       {{{{|0><0|_2}}}}
add_Output       {{{{|1><1|_2}}}}
"""


def random_pure_state(rng):
    th, ph = rng.uniform(0, math.pi), rng.uniform(0, 2 * math.pi)
    a, b = math.cos(th / 2), complex(math.cos(ph), math.sin(ph)) * math.sin(th / 2)
    rho01 = a * b.conjugate()
    return (f"{{{a * a:.12f}*|0><0|_2 + ({rho01.real:.12f}+{rho01.imag:.12f}*i)*|0><1|_2 + "
            f"({rho01.real:.12f}-{rho01.imag:.12f}*i)*|1><0|_2 + {abs(b) ** 2:.12f}*|1><1|_2}}")


def write_dephasing_context(path, rng, te, dt, nintermediate, detuning):
    """Pure dephasing: no pulse, random detuning and pure initial state, coherence |0><1|.
    Exact property: populations are constant in time."""
    with open(path, 'w') as f:
        f.write(f"""# generated by run_benchmark.py: pure dephasing
ta {0}
dt {dt}
te {te}
Nintermediate {nintermediate}
initial          {random_pure_state(rng)}
add_Hamiltonian  {{{-1.5 + rng.uniform(*detuning):.10f}*|1><1|_2}}
{OUTPUTS.format(obs='|0><1|_2')}""")


def write_ood_context(path, rng, te, dt, nintermediate, area, detuning):
    """Out-of-distribution context: two Gaussian pulses, random pure initial state."""
    pulses = ''
    for t0 in (0.3 * te, 0.65 * te):
        pulses += (f"add_Pulse Gauss  {t0} {te / 10} {{{rng.uniform(*area):.10f}*pi}} "
                   f"{rng.uniform(*detuning):.10f}   {{hbar/2*|1><0|_2}}\n")
    with open(path, 'w') as f:
        f.write(f"""# generated by run_benchmark.py: OOD (two pulses, random pure initial state)
ta {0}
dt {dt}
te {te}
Nintermediate {nintermediate}
initial          {random_pure_state(rng)}
add_Hamiltonian  {{-1.5*|1><1|_2}}
{pulses}{OUTPUTS.format(obs='|1><1|_2')}""")


def simulate(ctx, pt, outfile):
    run([ACE, ctx, '-add_PT', pt, '-outfile', outfile, '-set_precision', '14'])
    t, obs, tr, pop = [], [], [], []
    with open(outfile) as f:
        for line in f:
            v = line.split()
            if len(v) < 7:
                continue
            t.append(float(v[0]))
            obs.append(complex(float(v[1]), float(v[2])))
            tr.append(complex(float(v[3]) + float(v[5]), float(v[4]) + float(v[6])))
            pop.append(float(v[5]))
    return t, obs, tr, pop


def maxdim_of(pt):
    _, out = run([os.path.join(TOOLS, 'PTB_analyze'), '-read_PT', pt])
    for line in out.splitlines():
        if line.startswith('Maxdim'):
            return int(line.split()[1])
    return -1


def hs_rel(pt_in, pt):
    """||T_in - T||_HS / ||T_in||_HS (dictionary multiplicities)"""
    _, out = run([os.path.join(TOOLS, 'PTB_HS_distance'), '-read_PT', pt_in, '-compare_PT', pt])
    return float(next(l.split()[1] for l in out.splitlines() if l.startswith('relative')))


def errors(results, reference, names):
    fin, trace_sq, n_trace, trerr, drift = [], 0.0, 0, 0.0, 0.0
    for c in names:
        _, obs, tr, pop = results[c]
        _, obs_ref, _, _ = reference[c]
        drift = max(drift, max(abs(p - pop[0]) for p in pop))
        fin.append(abs(obs[-1] - obs_ref[-1]) ** 2)
        for a, b in zip(obs, obs_ref):
            trace_sq += abs(a - b) ** 2
            n_trace += 1
        trerr = max(trerr, max(abs(x - 1) for x in tr))
    return math.sqrt(sum(fin) / len(fin)), math.sqrt(trace_sq / n_trace), trerr, drift


def balanced_stats(logfile):
    amps, local = [], 0.0
    with open(logfile) as f:
        for row in csv.DictReader(f):
            if row['no_truncation'] == '1':
                continue
            amps.append(float(row['amplification']))
            local += float(row['local_error'])
    if not amps:
        return 0.0, 0.0, 0.0
    return max(amps), statistics.median(amps), local


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--pt', required=True, help='input PT (reference)')
    ap.add_argument('--te', type=float, required=True, help='end time matching the PT')
    ap.add_argument('--dt', type=float, default=0.1)
    ap.add_argument('--nintermediate', type=int, default=20)
    ap.add_argument('--t0', type=float, default=None, help='pulse center (default te/2)')
    ap.add_argument('--tau', type=float, default=None, help='pulse width (default te/5)')
    ap.add_argument('--area', type=float, nargs=2, default=[1., 5.], help='pulse area range in units of pi')
    ap.add_argument('--detuning', type=float, nargs=2, default=[-1., 1.], help='pulse detuning range (meV)')
    ap.add_argument('--n_train', type=int, default=8)
    ap.add_argument('--n_test', type=int, default=16)
    ap.add_argument('--n_ood', type=int, default=16, help='out-of-distribution contexts (other family)')
    ap.add_argument('--family', default='pulses', choices=['pulses', 'mixed', 'dephasing'],
                    help="training/test family: 'pulses' (single pulses, ground state, |1><1|), "
                         "'mixed' (single pulses; half random pure initial states; observable "
                         "|1><1|, sigma_x or sigma_y), 'dephasing' (no pulse, coherence). "
                         "OOD set: two pulses + random initial states ('pulses', 'mixed'), "
                         "single pulses ('dephasing')")
    ap.add_argument('--readout_stride', type=int, default=5, help='balanced_readout_stride')
    ap.add_argument('--seeds', type=int, nargs='+', default=None, help='several seeds (overrides --seed)')
    ap.add_argument('--jobs', type=int, default=1, help='parallel ACE simulations')
    ap.add_argument('--keep_pts', action='store_true', help='keep the truncated PT files')
    ap.add_argument('--maxk', type=int, nargs='+', default=[4, 6, 8, 12])
    ap.add_argument('--eta', type=float, nargs='+', default=[0., 0.3, 1.])
    ap.add_argument('--rhat', default='tw', choices=['tw', 'reference'])
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--outdir', required=True)
    ap.add_argument('--contexts_only', action='store_true',
                    help='only write the context files (<outdir>[/seed_<s>]/ctx) and exit')
    a = ap.parse_args()

    out_root = os.path.abspath(a.outdir)
    seeds = a.seeds if a.seeds else [a.seed]
    rows = []
    for seed in seeds:
        out = out_root if len(seeds) == 1 else os.path.join(out_root, f'seed_{seed}')
        rows += run_seed(a, seed, out)
    if a.contexts_only:
        return
    os.makedirs(out_root, exist_ok=True)
    with open(os.path.join(out_root, 'results.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {os.path.join(out_root, 'results.csv')}")


def run_seed(a, seed, out):
    os.makedirs(os.path.join(out, 'ctx'), exist_ok=True)
    os.makedirs(os.path.join(out, 'runs'), exist_ok=True)
    pt_in = os.path.abspath(a.pt)
    t0 = a.t0 if a.t0 is not None else a.te / 2
    tau = a.tau if a.tau is not None else a.te / 5

    rng = random.Random(seed)
    names = {'train': [], 'test': [], 'ood': []}

    def single_pulse(path):
        write_context(path, rng.uniform(*a.area), rng.uniform(*a.detuning), t0, tau, a.te, a.dt, a.nintermediate)

    def mixed_pulse(path):
        initial = random_pure_state(rng) if rng.random() < 0.5 else '{|0><0|_2}'
        write_context(path, rng.uniform(*a.area), rng.uniform(*a.detuning), t0, tau, a.te, a.dt, a.nintermediate,
                      initial=initial, obs=rng.choice(MIXED_OBSERVABLES))
    if a.family in ('pulses', 'mixed'):
        family = single_pulse if a.family == 'pulses' else mixed_pulse
        ood = lambda path: write_ood_context(path, rng, a.te, a.dt, a.nintermediate, a.area, a.detuning)
    else:
        family = lambda path: write_dephasing_context(path, rng, a.te, a.dt, a.nintermediate, a.detuning)
        ood = single_pulse
    for split, n, gen in (('train', a.n_train, family), ('test', a.n_test, family), ('ood', a.n_ood, ood)):
        for i in range(n):
            path = os.path.join(out, 'ctx', f'{split}_{i:02d}.param')
            gen(path)
            names[split].append(path)
    if a.contexts_only:
        return []
    allctx = names['train'] + names['test'] + names['ood']

    def evaluate(pt, tag):
        outs = {c: os.path.join(out, 'runs', f'{tag}_{os.path.basename(c)}.out') for c in allctx}
        with ThreadPoolExecutor(max_workers=max(1, a.jobs)) as ex:
            futures = {c: ex.submit(simulate, c, pt, outs[c]) for c in allctx}
            return {c: futures[c].result() for c in allctx}

    print(f"seed {seed}: reference {pt_in} (maxdim {maxdim_of(pt_in)})", flush=True)
    reference = evaluate(pt_in, 'ref')

    rows = []

    def record(method, maxk, eta, pt, runtime, stats=(None, None, None)):
        res = evaluate(pt, os.path.basename(pt))
        md = maxdim_of(pt)
        hs = hs_rel(pt_in, pt)
        for split in ('train', 'test', 'ood'):
            rf, rt, te_, dr = errors(res, reference, names[split])
            rows.append(dict(family=a.family, seed=seed, readout_stride=a.readout_stride, rhat=a.rhat,
                             method=method, maxk=maxk, eta='' if eta is None else eta, set=split,
                             rms_final=rf, rms_trace=rt, max_trace_err=te_, max_population_drift=dr,
                             maxdim=md, hs_rel=hs, runtime_s=runtime,
                             max_amplification='' if stats[0] is None else stats[0],
                             median_amplification='' if stats[1] is None else stats[1],
                             sum_local_error='' if stats[2] is None else stats[2]))
            print(f"  {method:9s} maxk={maxk:3d} eta={'' if eta is None else eta!s:4s} {split:5s}: "
                  f"rms_final={rf:.3e} rms_trace={rt:.3e} trace_err={te_:.1e} drift={dr:.1e} maxdim={md}", flush=True)

    for maxk in a.maxk:
        svd_pt = os.path.join(out, f'svd_{maxk}.pt')
        shutil.copyfile(pt_in, svd_pt)
        t_bw, _ = run([os.path.join(TOOLS, 'PTB_sweep_backward'), '-read_PT', svd_pt, '-threshold', '0', '-verbosity', '0'])
        t_fw, _ = run([os.path.join(TOOLS, 'PTB_sweep_forward'), '-read_PT', svd_pt, '-threshold', '0',
                       '-compress_maxk', str(maxk), '-verbosity', '0'])
        record('svd', maxk, None, svd_pt, t_bw + t_fw)

        for eta in a.eta:
            bal_pt = os.path.join(out, f'balanced_{maxk}_{eta}.pt')
            log = os.path.join(out, f'balanced_{maxk}_{eta}.csv')
            cmd = [os.path.join(TOOLS, 'PTB_balanced_truncate'), '-read_PT', pt_in, '-write_PT', bal_pt,
                   '-balanced_maxk', str(maxk), '-balanced_eta', str(eta), '-balanced_rhat', a.rhat,
                   '-balanced_readout_stride', str(a.readout_stride),
                   '-balanced_log', log, '-verbosity', '0']
            for c in names['train']:
                cmd += ['-add_balanced_context', c]
            t_b, _ = run(cmd)
            record('balanced', maxk, eta, bal_pt, t_b, balanced_stats(log))
        if not a.keep_pts:
            for f in os.listdir(out):
                if f.endswith('.pt') and f.startswith(('svd_', 'balanced_')):
                    os.remove(os.path.join(out, f))
    return rows


if __name__ == '__main__':
    main()
