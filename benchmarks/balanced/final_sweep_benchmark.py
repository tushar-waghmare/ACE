"""
End-to-end benchmark of the balanced final sweep in bin/ACE (Phase 7).

    python3 benchmarks/balanced/final_sweep_benchmark.py --jobs 9

Both arms run the same PT calculation (default template: bench30_thr1e-6_PT.param, i.e. 30
QD-phonon modes, threshold 1e-6, plus final_sweep_n 1; --template bench100_PT.param for 100 modes) and differ only in the last truncating operation:
  svd_<m>:              final_sweep_compress_maxk m        (plain ACE: SVD final sweep to m)
  balanced_<family>_<m>: balanced_final_sweep true, balanced_maxk m, balanced_eta 0.3,
                         training contexts of <family> (--ctxdir, default
                         results/bench30_thr1e-6_<family>/seed_1/ctx)
  base:                 no final target (common untruncated reference of both arms)
Every PT is built by bin/ACE from scratch (builds are skipped if the PT and its log exist).

Evaluation (all train/test/ood contexts of each family): errors against
  base   truncation error only (same calculation, no final target)
  tight  total error against a tighter PT (--tight, default bench30_thr3e-7.pt, if present)
  exact  pure dephasing only (train/test): independent boson model on the template's modes,
         Fock cutoff Boson_M
Output: results/final_sweep/results.csv, builds.csv (wall time, maxdim, HS error vs base).
"""
import argparse
import csv
import glob
import math
import os
import time
from concurrent.futures import ThreadPoolExecutor

import run_benchmark as rb

HERE = os.path.dirname(os.path.abspath(__file__))
TEMPLATE = os.path.join(HERE, 'bench30_thr1e-6_PT.param')


def template_value(key, template=None):
    for line in open(template or TEMPLATE):
        w = line.split()
        if len(w) >= 2 and w[0] == key:
            return w[1]
    return None


def build_param(path, write_pt, extra):
    lines = [l for l in open(TEMPLATE) if not l.startswith(('write_PT', 'outfile', '#'))]
    with open(path, 'w') as f:
        f.write(f'# generated by final_sweep_benchmark.py from {os.path.basename(TEMPLATE)}\n')
        f.writelines(lines)
        f.write(f'\nfinal_sweep_n 1\nwrite_PT {write_pt}\noutfile /dev/null\n{extra}')


def build(name, extra, out):
    pt = os.path.join(out, f'{name}.pt')
    log = os.path.join(out, f'{name}.log')
    par = os.path.join(out, f'{name}.param')
    if os.path.exists(pt) and os.path.exists(log) and 'build_seconds' in open(log).read():
        return name
    build_param(par, pt, extra)
    t0 = time.time()
    _, stdout = rb.run([rb.ACE, par], cwd=out)
    with open(log, 'w') as f:
        f.write(stdout)
        f.write(f'\nbuild_seconds {time.time() - t0:.1f}\n')
    return name


def build_seconds(out, name):
    for line in open(os.path.join(out, f'{name}.log')):
        if line.startswith('build_seconds'):
            return float(line.split()[1])
    return float('nan')


def main():
    global TEMPLATE
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--outdir', default=os.path.join(HERE, 'results', 'final_sweep'))
    ap.add_argument('--template', default=TEMPLATE, help='PT calculation parameter file')
    ap.add_argument('--ctxdir', default=os.path.join(HERE, 'results', 'bench30_thr1e-6_{family}', 'seed_{seed}', 'ctx'),
                    help='context directory pattern ({family}, {seed})')
    ap.add_argument('--tight', default=os.path.join(HERE, 'bench30_thr3e-7.pt'),
                    help="tighter reference PT ('' or missing file: skipped)")
    ap.add_argument('--targets', type=int, nargs='+', default=[8, 12, 16, 24])
    ap.add_argument('--families', nargs='+', default=['mixed', 'dephasing'])
    ap.add_argument('--eta', type=float, default=0.3)
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--jobs', type=int, default=8)
    a = ap.parse_args()
    TEMPLATE = os.path.abspath(a.template)
    out = os.path.abspath(a.outdir)
    os.makedirs(out, exist_ok=True)

    ctx = {}
    for fam in a.families:
        d = os.path.abspath(a.ctxdir.format(family=fam, seed=a.seed))
        ctx[fam] = {s: sorted(glob.glob(os.path.join(d, f'{s}_*.param'))) for s in ('train', 'test', 'ood')}

    jobs = [('base', '')]
    for m in a.targets:
        jobs.append((f'svd_{m}', f'final_sweep_compress_maxk {m}\n'))
        for fam in a.families:
            name = f'balanced_{fam}_{m}'
            extra = (f'balanced_final_sweep true\nbalanced_maxk {m}\nbalanced_eta {a.eta}\n'
                     f'balanced_readout_stride 5\nbalanced_log {name}_cuts.csv\n'
                     f'balanced_timing {name}_timing.csv\n')
            extra += ''.join(f'add_balanced_context {c}\n' for c in ctx[fam]['train'])
            jobs.append((name, extra))
    print(f'{len(jobs)} builds, {a.jobs} in parallel', flush=True)
    with ThreadPoolExecutor(max_workers=a.jobs) as ex:
        for name in ex.map(lambda j: build(j[0], j[1], out), jobs):
            print(f'  built {name} ({build_seconds(out, name):.0f} s)', flush=True)

    base = os.path.join(out, 'base.pt')
    tight = a.tight
    brow = []
    for name, _ in jobs:
        pt = os.path.join(out, f'{name}.pt')
        brow.append(dict(name=name, build_seconds=build_seconds(out, name), maxdim=rb.maxdim_of(pt),
                         hs_rel_vs_base=0. if name == 'base' else rb.hs_rel(base, pt)))
    with open(os.path.join(out, 'builds.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(brow[0].keys()))
        w.writeheader()
        w.writerows(brow)

    runs = os.path.join(out, 'runs')
    os.makedirs(runs, exist_ok=True)
    rows = []
    for fam in a.families:
        allctx = ctx[fam]['train'] + ctx[fam]['test'] + ctx[fam]['ood']

        def evaluate(pt, tag):
            with ThreadPoolExecutor(max_workers=a.jobs) as ex:
                fut = {c: ex.submit(rb.simulate, c, pt, os.path.join(runs, f'{tag}_{fam}_{os.path.basename(c)}.out'))
                       for c in allctx}
                return {c: fut[c].result() for c in allctx}
        refs = {'base': evaluate(base, 'base')}
        if tight and os.path.exists(tight):
            refs['tight'] = evaluate(tight, 'tight')
        exact = exact_reference(fam, ctx[fam], refs['base']) if fam == 'dephasing' else None
        pts = [('base', '', 'base')] + [(m_name, m, f'{m_name}_{m}') for m in a.targets
                                        for m_name in ('svd', 'balanced')]
        for method, m, name in pts:
            if method == 'balanced':
                name = f'balanced_{fam}_{m}'
            res = refs['base'] if name == 'base' else evaluate(os.path.join(out, f'{name}.pt'), name)
            for ref_name, ref in list(refs.items()) + ([('exact', exact)] if exact else []):
                for split in ('train', 'test', 'ood'):
                    names = [c for c in ctx[fam][split] if c in ref]
                    if not names:
                        continue
                    rf, rt, tr, _ = rb.errors(res, ref, names)
                    rows.append(dict(family=fam, method=method, maxk=m, reference=ref_name, set=split,
                                     rms_final=rf, rms_trace=rt, max_trace_err=tr))
            print(f'  evaluated {fam} {name}', flush=True)
    with open(os.path.join(out, 'results.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print(f'wrote {out}/results.csv, {out}/builds.csv')


def exact_reference(fam, ctxs, like):
    """exact pure-dephasing trajectories in the format of rb.simulate (train/test only)"""
    import numpy as np
    import exact_dephasing as ed
    import tempfile
    # ed.ace_modes reproduces the discretization of the bench*_PT.param bath (QDPhonon, E_max 5,
    # no polaron-shift subtraction, T = 4); refuse other templates instead of comparing to the wrong model
    fixed = dict(Boson_J_type='QDPhonon', Boson_E_max='5', Boson_subtract_polaron_shift='false', temperature='4')
    for k, v in fixed.items():
        if template_value(k) != v:
            raise ValueError(f'exact reference needs {k} {v} in {TEMPLATE} (found {template_value(k)})')
    n_modes, fock_m = int(template_value('Boson_N_modes')), int(template_value('Boson_M'))
    E, g = ed.ace_modes(n_modes, tempfile.mkdtemp(prefix='exact_'))
    ref = {}
    for c in ctxs['train'] + ctxs['test']:
        t, obs, tr, pop = like[c]
        E1, rho10 = ed.parse_context(c)
        tt = np.array(t)
        ex = rho10 * np.exp(-1j * E1 * tt / ed.HBAR) * ed.bath_factor(E, g, fock_m, 4., tt)
        ref[c] = (t, list(ex), [1.] * len(t), pop)
    return ref


if __name__ == '__main__':
    main()
